#!/usr/bin/env bash
# Runs a fixed benchmark matrix against a local 3-node cluster and writes a markdown report.
#
#   scripts/bench_cluster.sh [OUTPUT]          (default OUTPUT: docs/benchmark-results.md)
#
# Settings (environment, all optional):
#   BENCH_OPS      operations per run (default 800)
#   BENCH_VALUE    value size in bytes (default 100)
#   BENCH_THREADS  client thread counts to try (default "1 4 8 32")
#   BENCH_CONFIGS  which node configurations to run (default "durable nosync")
#                    durable = the default node: every write is fsynced on a majority
#                    nosync  = --no-sync: nothing is fsynced (shows the cost of durability)
#   RAFTKV_BIN, RAFTKV_DIR, RAFTKV_BASE_PORT are passed through to scripts/run_cluster.sh.
#
# All three nodes run on this one machine and share its disk and CPU, so the numbers describe this
# machine, not a real deployment. Works with the bash 3.2 that ships with macOS.
set -u

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
CLUSTER="$ROOT/scripts/run_cluster.sh"
OUT="${1:-$ROOT/docs/benchmark-results.md}"
OPS="${BENCH_OPS:-800}"
VALUE="${BENCH_VALUE:-100}"
THREADS="${BENCH_THREADS:-1 4 8 32}"
CONFIGS="${BENCH_CONFIGS:-durable nosync}"

cleanup() { "$CLUSTER" stop >/dev/null 2>&1; }
trap cleanup EXIT INT TERM

flags_for() {
  case "$1" in
    durable) echo "" ;;
    nosync) echo "--no-sync" ;;
    *) echo "unknown configuration: $1" >&2; exit 2 ;;
  esac
}

machine() {
  if [ "$(uname -s)" = "Darwin" ]; then
    local cpu cores mem
    cpu="$(sysctl -n machdep.cpu.brand_string 2>/dev/null)"
    cores="$(sysctl -n hw.ncpu 2>/dev/null)"
    mem="$(( $(sysctl -n hw.memsize 2>/dev/null || echo 0) / 1073741824 ))"
    echo "$cpu, $cores cores, ${mem} GiB, $(sw_vers -productName 2>/dev/null) $(sw_vers -productVersion 2>/dev/null)"
  else
    local cpu
    cpu="$(grep -m1 'model name' /proc/cpuinfo 2>/dev/null | cut -d: -f2 | sed 's/^ *//')"
    echo "${cpu:-unknown CPU}, $(nproc 2>/dev/null || echo '?') cores, $(uname -sr)"
  fi
}

wait_for_leader() {
  local i=0
  while [ $i -lt 100 ]; do
    if "$CLUSTER" leader >/dev/null 2>&1; then return 0; fi
    sleep 0.1
    i=$((i + 1))
  done
  return 1
}

# One bench run; prints a markdown table row (or a row saying it failed).
run_one() {
  local config="$1" op="$2" threads="$3" out line
  out="$("$CLUSTER" cli bench "$op" "$OPS" "$VALUE" "$threads" 2>&1)"
  line="$(printf '%s\n' "$out" | grep '^throughput ')"
  if [ -z "$line" ]; then
    echo "| $config | $op | $threads | failed | | | | |"
    printf '%s\n' "$out" | tail -3 >&2
    return
  fi
  # throughput 60.5 ops/s   latency ms: p50 16.56  p95 22.29  p99 26.30  max 31.04
  printf '%s\n' "$line" | awk -v c="$config" -v o="$op" -v t="$threads" \
    '{ printf "| %s | %s | %s | %s | %s | %s | %s | %s |\n", c, o, t, $2, $7, $9, $11, $13 }'
}

rows=""
for config in $CONFIGS; do
  flags="$(flags_for "$config")"
  echo "== $config: starting a 3-node cluster ${flags:+(flags: $flags)}" >&2
  "$CLUSTER" stop >/dev/null 2>&1
  "$CLUSTER" clean >/dev/null 2>&1
  if ! RAFTKV_NODE_FLAGS="$flags" "$CLUSTER" start 3 >/dev/null 2>&1; then
    echo "could not start the cluster; build it first (build-net, network option ON)" >&2
    exit 1
  fi
  if ! wait_for_leader; then echo "no leader elected within 10 s" >&2; exit 1; fi
  "$CLUSTER" cli bench put 50 "$VALUE" 1 >/dev/null 2>&1  # warm up connections and the log
  for threads in $THREADS; do
    for op in put get; do
      echo "   $op, $threads thread(s)" >&2
      rows="$rows$(run_one "$config" "$op" "$threads")
"
    done
  done
  "$CLUSTER" stop >/dev/null 2>&1
done
"$CLUSTER" clean >/dev/null 2>&1

rev="$(git -C "$ROOT" rev-parse --short HEAD 2>/dev/null || echo unknown)"
{
  echo "# Cluster benchmark results"
  echo
  echo "Generated by \`scripts/bench_cluster.sh\` on $(date '+%Y-%m-%d %H:%M %Z') at commit \`$rev\`."
  echo
  echo "| | |"
  echo "|---|---|"
  echo "| Machine | $(machine) |"
  echo "| Cluster | 3 \`raftkv_node\` processes on this one machine (shared disk and CPU) |"
  echo "| Workload | $OPS operations per run, ${VALUE}-byte values; \`put\` writes distinct keys, \`get\` reads one key per thread |"
  echo "| Configurations | \`durable\`: default node, every write fsynced on a majority. \`nosync\`: \`--no-sync\`, nothing fsynced |"
  echo
  echo "Each row is one run of \`raftkv_cli bench\`: throughput over the run, and per-operation latency"
  echo "percentiles in milliseconds, measured by the client from request to answer. A \`get\` is"
  echo "linearizable (ReadIndex), so it also talks to a majority."
  echo
  echo "| Config | Op | Threads | Ops/s | p50 ms | p95 ms | p99 ms | max ms |"
  echo "|---|---|---|---|---|---|---|---|"
  printf '%s' "$rows"
  echo
  echo "Single runs on a laptop vary by 10-20%; repeat a run before reading much into a small difference."
} > "$OUT"
echo "wrote $OUT" >&2
